import streamlit as st
import cv2
import numpy as np
import json
import time

# --- CONFIGURATION ---
st.set_page_config(
    page_title="TIA Kiosk",
    page_icon="🏧",
    layout="centered",
    initial_sidebar_state="collapsed"
)

# --- CUSTOM CSS FOR MOBILE LOOK ---
# This makes the app look like a dark-mode physical machine interface
st.markdown("""
    <style>
    .stApp { background-color: #000000; color: white; }
    .block-container { padding-top: 2rem; }
    h1 { color: #00A67E; text-align: center; font-size: 2rem; }
    .stCameraInput { border: 2px solid #00A67E; border-radius: 10px; }
    
    /* Success Box Styling */
    .success-box {
        background-color: #155724; 
        color: #d4edda; 
        padding: 20px; 
        border-radius: 10px; 
        text-align: center;
        border: 2px solid #c3e6cb; 
        margin-top: 20px;
        animation: fadeIn 1s;
    }
    
    @keyframes fadeIn {
      0% { opacity: 0; transform: translateY(20px); }
      100% { opacity: 1; transform: translateY(0); }
    }
    </style>
""", unsafe_allow_html=True)

# --- HEADER ---
st.title("🏧 TIA SIM KIOSK")
st.caption("Scan the QR Code from your Chatbot to collect your SIM.")

st.divider()

# --- CAMERA INPUT (THE SCANNER) ---
# Streamlit's camera input acts as the scanner. 
# On a phone, this opens the native camera.
img_file_buffer = st.camera_input("Scan QR Code")

if img_file_buffer:
    # 1. Convert the photo buffer to an OpenCV Image
    bytes_data = img_file_buffer.getvalue()
    cv2_img = cv2.imdecode(np.frombuffer(bytes_data, np.uint8), cv2.IMREAD_COLOR)
    
    # 2. Detect QR Code
    detector = cv2.QRCodeDetector()
    data, bbox, _ = detector.detectAndDecode(cv2_img)
    
    if data:
        # 3. VALIDATION LOGIC
        try:
            # We expect JSON data from the QR code generated by the main app
            sim_data = json.loads(data)
            
            # Security Check: Ensure it's our specific token type
            if sim_data.get("type") == "TIA_SIM_TOKEN":
                
                # --- SIMULATION: DISPENSING ANIMATION ---
                with st.spinner("🔄 Verifying Token..."):
                    time.sleep(1)
                
                with st.spinner("⚙️ Writing SIM Card ICCID..."):
                    time.sleep(1.5)
                
                # Visual Feedback
                st.balloons()
                
                st.markdown(f"""
                <div class="success-box">
                    <h2>✅ SIM DISPENSED</h2>
                    <p style="font-size: 1.2rem;"><strong>Phone:</strong> {sim_data.get('phone', 'Unknown')}</p>
                    <p><strong>Passport:</strong> {sim_data.get('passport', 'Unknown')}</p>
                    <p><strong>Plan:</strong> {sim_data.get('plan', 'Standard')}</p>
                    <hr>
                    <p style="font-size: 0.8rem;">Please take your active SIM card from the tray below.</p>
                </div>
                """, unsafe_allow_html=True)
                
            else:
                st.error("❌ Invalid QR Code. This code is not recognized by the TIA Kiosk system.")
                
        except json.JSONDecodeError:
            # Fallback if the QR code isn't JSON
            st.warning(f"⚠️ Scanned Data: {data}")
            st.error("Error: Not a valid TIA SIM Token.")
    else:
        st.info("⚠️ No QR Code detected in the image. Please try holding the camera steady.")